"""
以下の仕様に基づいてコードを1から作成してみましょう。模擬問題のコードを参考にしてもOKです。

a という変数に次のリストを代入してください
[2.02, 2.03, 2.04]
次にb という変数に次のリストを代入してください
[2.05, 2.06, -2.07]

aとbのリストを結合して変数cに代入してください
関数を使ってcの最大値を求めてください
関数を使ってc[2:5]の最小値を求めてください

c[2]を小数第1位に丸めて出力してください
c[5]を小数第1位に丸めて出力してください
round()関数を使うとよいでしょう。

【出力例】
2.06
2.04
2.0
-2.1
"""

a = [2.02, 2.03, 2.04]
b = [2.05, 2.06, -2.07]
c = a + b

list_max = max(c)
slice_min = min(c[2:5])
print(list_max)
print(slice_min)

result1 = round(c[2],1)
result2 = round(c[5],1)
print(result1)
print(result2)
