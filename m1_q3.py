a=12
b=5
print(b-a)  # ...(12)イ:-7
print(b-abs(2 *b-a)*3)  # ...(13)イ:-1
print("{0:05b}".format(b))  # ...(14)ア:00101
c=[2,7,15,12,9]
c.sort()
print(c)    # ...(15)ア:[2,7,9,12,15]
print(c[2:3])   #...(16)ウ:[9]
print(f'{(a-b) / c[3]:->8.3f}') # ...(17)ア:---0.583
'''
フォーマット指定について
-:埋め文字。余った桁を"-"で埋める。
>:右揃え
8:全体の桁を8文字にする
.3:小数点以下を3桁まで表示。
f:floatとして表示
'''